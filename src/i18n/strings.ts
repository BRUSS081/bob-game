export type Lang = 'en' | 'it' | 'pt';
export const LANGS: readonly Lang[] = ['en', 'it', 'pt'];
/** Each language by its own name. */
export const LANG_NAMES: Record<Lang, string> = { en: 'ENGLISH', it: 'ITALIANO', pt: 'PORTUGUÊS' };

export function isLang(v: unknown): v is Lang {
  return v === 'en' || v === 'it' || v === 'pt';
}
export const STRINGS: Record<Lang, Strings> = { en: EN, it: IT, pt: PT };

/** The strings of the current language: a live binding, so every screen sees a change at once. */
export let t: Strings = EN;
export let lang: Lang = 'en';

export function setLang(next: Lang): void {
  lang = next;
  t = STRINGS[next];
  if (typeof document !== 'undefined') document.documentElement.lang = next;
}

/** The device's language when we have it, English otherwise. */
export function deviceLang(languages: readonly string[] = typeof navigator === 'undefined' ? [] : navigator.languages ?? [navigator.language]): Lang {
  for (const l of languages) {
    const code = (l ?? '').slice(0, 2).toLowerCase();
    if (code === 'it' || code === 'pt' || code === 'en') return code;
  }
  return 'en';
}
